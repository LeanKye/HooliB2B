export type Template = {
  slug: string;
  name: string;
  kind: "card" | "full"; // визитка или полноценный сайт
  industry: string;
  /** Одним предложением: что это и кто этим пользуется. */
  summary: string;
  /** Для кого шаблон: ниша, масштаб, задача. Отвечает на «подойдёт ли мне». */
  whoFor: string;
  /** Короткий перечень блоков — что уже есть в шаблоне до кастомизации. */
  blocks: string[];
  /** Разбор каждого блока: зачем он нужен бизнесу. */
  blockNotes: { block: string; note: string }[];
  /** Что меняем под клиента — чтобы было видно, что это не «копипаст». */
  customizes: string[];
  /** Какой контент нужен от клиента для запуска. */
  needsAssets: string[];
  /** Плейсхолдеры скриншотов: подпись + что должно быть на кадре. */
  shots: { caption: string; hint: string }[];
  accent: string;
  /** Подробные макеты экранов: ставим у первого проработанного шаблона. */
  detailed?: boolean;
  /** Оттенки для CSS-макета превью: [фон, акцент, третий] */
  preview: [string, string, string];
};

